#!/usr/bin/env bash
# ==============================================================================
# SnoozeML Multi-Model Setup & Concurrent GPU Benchmark Runner
#
# Sets up three heterogeneous models:
#   1. bge_small       - BAAI General Embedding (Hugging Face Candle Safetensors, GPU)
#   2. cancer_xgboost  - Breast Cancer Classifier (Pure-Rust GBDT Tree via hessboost)
#   3. chronos_bolt    - Amazon Chronos-Bolt Forecasting (Process-Isolated Python Worker)
#
# Launches the CUDA container (if not running) and drives concurrent load
# across all models simultaneously so you can inspect real-time GPU compute in nvtop.
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

PORT="${SNOOZE_PORT:-8082}"
ENDPOINT="http://localhost:${PORT}"
DURATION="${DURATION:-30}"
CONCURRENCY="${CONCURRENCY:-8}"
MODELS_DIR="${ROOT_DIR}/models"

echo "========================================================================"
echo "  SnoozeML Multi-Model Setup & GPU Benchmark"
echo "========================================================================"
echo "  Models Root:           ${MODELS_DIR}"
echo "  Target Endpoint:       ${ENDPOINT}"
echo "  Concurrency / Model:   ${CONCURRENCY}"
echo "  Test Duration:         ${DURATION}s"
echo "========================================================================"

mkdir -p "${MODELS_DIR}"
chmod 777 "${MODELS_DIR}" 2>/dev/null || true

# ------------------------------------------------------------------------------
# 1. Setup Model 1: BGE Encoder (Candle Safetensors on CUDA)
# ------------------------------------------------------------------------------
if [ ! -f "${MODELS_DIR}/bge_small/model.safetensors" ]; then
    echo "[*] Downloading BAAI/bge-small-en-v1.5 encoder weights via snooze download..."
    docker run --rm \
        -v "${MODELS_DIR}:/models" \
        snooze-ml:cuda download BAAI/bge-small-en-v1.5 \
        --models-dir /models \
        --name bge_small \
        --include "*.safetensors" \
        --include "config.json" \
        --include "tokenizer.json" \
        --no-init
else
    echo "[+] Model 1/3 (bge_small): Found existing weights in ${MODELS_DIR}/bge_small"
fi

# ------------------------------------------------------------------------------
# 2. Setup Model 2: XGBoost GBDT Tree Model
# ------------------------------------------------------------------------------
if [ ! -f "${MODELS_DIR}/cancer_xgboost.xgb.json" ]; then
    echo "[*] Training Breast Cancer XGBoost model using tools/train_tree.py..."
    # Check if host python has xgboost & scikit-learn; else use temporary container/venv
    if python3 -c "import xgboost, sklearn" 2>/dev/null; then
        python3 "${ROOT_DIR}/tools/train_tree.py" --dataset breast_cancer --name cancer_xgboost
    else
        echo "[*] Running training in lightweight runner..."
        docker run --rm \
            -v "${ROOT_DIR}:/app" \
            -w /app \
            --entrypoint /bin/sh \
            snooze-ml:cuda -c "
                /opt/venv/bin/pip install --quiet xgboost scikit-learn && \
                /opt/venv/bin/python tools/train_tree.py --dataset breast_cancer --name cancer_xgboost
            "
    fi
else
    echo "[+] Model 2/3 (cancer_xgboost): Found existing tree model in ${MODELS_DIR}/cancer_xgboost.xgb.json"
fi

# ------------------------------------------------------------------------------
# 3. Setup Model 3: Chronos-Bolt (Custom Python Worker)
# ------------------------------------------------------------------------------
CHRONOS_DIR="${MODELS_DIR}/chronos_bolt"
mkdir -p "${CHRONOS_DIR}"

if [ ! -f "${CHRONOS_DIR}/snooze_model.py" ]; then
    echo "[*] Copying Chronos-Bolt worker runner to ${CHRONOS_DIR}..."
    cp "${ROOT_DIR}/examples/chronos_bolt/snooze_model.json" "${CHRONOS_DIR}/"
fi
echo "[+] Model 3/3 (chronos_bolt): Python worker runner ready in ${CHRONOS_DIR}"

# ------------------------------------------------------------------------------
# 4. Generate Unified models.toml
# ------------------------------------------------------------------------------
cat << 'EOF' > "${MODELS_DIR}/models.toml"
# SnoozeML Multi-Model Configuration
# Automatically generated by tools/setup_and_benchmark.sh

[defaults]
idle_timeout_secs = 300
max_batch_size = 16
max_batch_delay_ms = 10
device = "auto"
min_residency_secs = 10

[[models]]
id = "bge_small"
path = "bge_small/model.safetensors"
description = "BAAI General Embedding model (Candle Safetensors, GPU)"
device = "cuda"
max_batch_size = 16
max_batch_delay_ms = 10
idle_timeout_secs = 300

[[models]]
id = "cancer_xgboost"
path = "cancer_xgboost.xgb.json"
description = "Breast Cancer binary classification (Pure-Rust GBDT Tree)"
device = "tree"
max_batch_size = 64
max_batch_delay_ms = 5
idle_timeout_secs = 300

[[models]]
id = "chronos_bolt"
path = "chronos_bolt"
description = "Amazon Chronos-Bolt probabilistic forecasting (Process-Isolated Python Worker)"
device = "cuda"
max_batch_size = 8
max_batch_delay_ms = 15
idle_timeout_secs = 120
EOF
echo "[+] Wrote unified configuration to ${MODELS_DIR}/models.toml"

# ------------------------------------------------------------------------------
# 5. Start CUDA Docker Container (if not already running)
# ------------------------------------------------------------------------------
CONTAINER_NAME="snooze-cuda"
if ! docker ps --format '{{.Names}}' | grep -q "^${CONTAINER_NAME}$"; then
    echo "[*] Starting ${CONTAINER_NAME} container via docker-compose..."
    cd "${ROOT_DIR}"
    docker compose --profile cuda up -d snooze-cuda
fi

# Ensure real PyTorch and Chronos-Bolt dependencies are present in the container
if ! docker exec "${CONTAINER_NAME}" /opt/venv/bin/python -c "import torch, chronos" 2>/dev/null; then
    echo "[*] Installing C compiler and Python headers for Triton JIT..."
    docker exec -u 0 "${CONTAINER_NAME}" sh -c "apt-get update && apt-get install -y --no-install-recommends gcc libc6-dev python3-dev"
    echo "[*] Installing PyTorch and chronos-forecasting inside ${CONTAINER_NAME}..."
    docker exec "${CONTAINER_NAME}" /opt/venv/bin/pip install --no-cache-dir torch chronos-forecasting
fi

echo "[*] Awaiting server readiness on ${ENDPOINT}..."
ATTEMPTS=0
MAX_ATTEMPTS=30
until curl -s -f "${ENDPOINT}/health/live" >/dev/null 2>&1 || [ ${ATTEMPTS} -ge ${MAX_ATTEMPTS} ]; do
    sleep 1
    ATTEMPTS=$((ATTEMPTS + 1))
done

if [ ${ATTEMPTS} -ge ${MAX_ATTEMPTS} ]; then
    echo "[ERROR] SnoozeML failed to start within ${MAX_ATTEMPTS}s at ${ENDPOINT}" >&2
    echo "Check container logs: docker logs ${CONTAINER_NAME}" >&2
    exit 1
fi

echo "[+] SnoozeML daemon is LIVE on ${ENDPOINT}!"
echo ""
echo "========================================================================"
echo "  🚀 GPU MONITORING TIP:"
echo "  Open a separate terminal window or tmux pane NOW and run:"
echo ""
echo "      nvtop"
echo ""
echo "  Watch real-time GPU utilization %, VRAM usage, and active processes"
echo "  as all three models run concurrently under dynamic micro-batching!"
echo "========================================================================"
echo ""
read -t 5 -p "Press ENTER to begin concurrent benchmark immediately (or wait 5s)..." || true
echo ""

# ------------------------------------------------------------------------------
# 6. Execute Concurrent Multi-Model Benchmark
# ------------------------------------------------------------------------------
python3 "${SCRIPT_DIR}/concurrent_benchmark.py" \
    --endpoint "${ENDPOINT}" \
    --models "bge_small,cancer_xgboost,chronos_bolt" \
    --concurrency-per-model "${CONCURRENCY}" \
    --duration "${DURATION}"
